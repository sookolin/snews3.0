#: Used when nothing matches.
_DEFAULT = "📰"


def guess_emoji(title: str | None, text: str = "") -> str:
    """Return an emoji matching the headline, or a neutral news icon."""
    blob = f"{title or ''} {text[:400]}".lower()
    for emoji, keywords in _RULES:
        if any(keyword in blob for keyword in keywords):
            return emoji
    return _DEFAULT
